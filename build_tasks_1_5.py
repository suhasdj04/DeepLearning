            "class CustomBatchNormFunction:\n",
            "    @staticmethod\n",
            "    def forward(x, gamma, beta, running_mean, running_var, eps=1e-5, training=True, momentum=0.1):\n",
            "        # x shape: (N, D)\n",
            "        if training:\n",
            "            mean = x.mean(dim=0)\n",
            "            var = x.var(dim=0, unbiased=False)\n",
