            "            return stable_softmax(self.Z_cache)\n",
            "        else:\n",
            "            return self.Z_cache\n",
            "            \n",
            "    def backward(self, dA):\n",
            "        # Backward pass: compute local derivatives and gradients w.r.t parameters\n",
            "        m = self.X_cache.shape[0]\n",
            "        \n",
            "        # Compute dZ = dLoss/dZ\n",
