            "        self.db = np.sum(dZ, axis=0, keepdims=True) / m\n",
            "        \n",
            "        # Return dA_prev to propagate back to previous layers\n",
            "        dA_prev = np.dot(dZ, self.W.T)\n",
            "        return dA_prev\n",
