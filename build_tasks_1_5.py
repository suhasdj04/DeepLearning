            "        self.kh = self.kw = kernel_size\n",
            "        self.padding = padding\n",
            "        self.stride = stride\n",
            "        \n",
            "        # Initialize parameters\n",
            "        self.W = np.random.randn(out_channels, in_channels, self.kh, self.kw) * np.sqrt(2.0 / (in_channels * self.kh * self.kw))\n",
